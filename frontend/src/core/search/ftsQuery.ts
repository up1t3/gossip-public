/**
 * Санитизация пользовательского ввода в FTS5 MATCH-запрос.
 *
 * FTS5 чувствителен к спецсимволам (' " ^ * : ( )), которые ломают запрос.
 * Стратегия:
 *  - убрать кавычки и апострофы (они не несут смысловой нагрузки в поиске,
 *    но ломают синтаксис FTS5);
 *  - остальные FTS-спецсимволы (^ : ( )) вырезать;
 *  - добавить '*' в конце для prefix-match (найдёт 'hello' по 'hel'), если
 *    термин ещё не заканчивается на '*';
 *  - пустой/только-пробелы ввод → '' (вызывающий код трактует как «нет запроса»).
 *
 * Вынесено в отдельный модуль без side-effect-импортов (storageManager/sql.js),
 * чтобы Playwright мог импортировать функцию напрямую без загрузки WASM.
 */
export function sanitizeFtsQuery(raw: string): string {
  // 1. Убираем кавычки/апострофы и FTS-спецсимволы
  const stripped = raw
    .replace(/['"`]/g, ' ')   // кавычки/апостроф → пробел (CS-S2: O'Brien → O Brien)
    .replace(/[\^:()]/g, ' ') // FTS-операторы → пробел
    .trim();

  if (stripped === '') return ''; // CS-S3

  // 2. Collapse внутренних пробелов
  const collapsed = stripped.replace(/\s+/g, ' ');

  // 3. Prefix-match: добавляем '*' если ещё нет (CS-S4 — не дублируем)
  return collapsed.endsWith('*') ? collapsed : `${collapsed}*`;
}
